function cap = conductor_diameter(d_Co)
%ILETKEN_CAPI  Rounds the computed wire diameter up to the next standard
%   bare-wire diameter (range-checked). Instead of returning 0 when out of
%   range, a defined error (imDesign:iletkenCapi:*) is thrown.

    ciplak_tel = [0 0.040 0.045 0.050 0.056 0.063 0.071 0.080 0.090 0.100 ...
        0.112 0.125 0.140 0.160 0.180 0.200 0.224 0.240 0.250 0.270 0.280 ...
        0.315 0.355 0.400 0.450 0.500 0.560 0.630 0.710 0.750 0.800 0.850 ...
        0.900 0.950 1.000 1.050 1.100 1.120 1.150 1.180 1.200 1.250 1.300 ...
        1.400 1.500 1.600 1.700 1.800 1.900 2.000 2.100 2.120 2.200 2.240 ...
        2.300 2.360 2.400 2.500 2.600 2.650 2.700 2.800 2.900 3.000 3.150 ...
        3.200 3.350 3.400 3.550 3.600 3.750 3.800 4.000 4.200 4.250 4.400 ...
        4.500 4.600 4.750 4.800 5.000];

    if ~isscalar(d_Co) || ~isfinite(d_Co) || ~isreal(d_Co)
        error('imDesign:iletkenCapi:badInput', ...
            'd_Co must be scalar and finite (given: %g).', d_Co);
    end

    if d_Co <= ciplak_tel(1) || d_Co > ciplak_tel(end)
        error('imDesign:iletkenCapi:outOfRange', ...
            'd_Co = %g mm is outside the standard wire range (%g, %g].', ...
            d_Co, ciplak_tel(1), ciplak_tel(end));
    end

    % Round up to the next standard diameter (pick the first value >= d_Co)
    k = find(ciplak_tel >= d_Co, 1, 'first');
    cap = ciplak_tel(k);
end
